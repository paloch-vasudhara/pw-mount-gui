export const COMBO_FLAG_MAP: Record<string, readonly string[]> = {
  CHBZ: ['CN', 'BR'],
  CHTU: ['CN', 'TR'],
  FRIT: ['FR', 'IT'],
  FGER: ['FR', 'DE'],
  GRSA: ['GR', 'SA'],
  PRES: ['CN', 'EU'],
  SGJP: ['SG', 'JP'],
  STCT: ['SG', 'TW'],
  TMMC: ['TM', 'MC'],
  USBZ: ['US', 'BR'],
}

export type FlagSource =
  | { kind: 'combo', leftIso: string, rightIso: string }
  | { kind: 'single', iso: string }
  | null

export function resolveFlag(ownerCode: string | null | undefined): FlagSource {
  if (!ownerCode) return null
  const code = ownerCode.toUpperCase()
  const combo = COMBO_FLAG_MAP[code]
  if (combo) return { kind: 'combo', leftIso: combo[0]!.toLowerCase(), rightIso: combo[1]!.toLowerCase() }
  const iso = OWNER_TO_ISO[code] ?? code
  if (iso.length !== 2 || iso === 'XX') return null
  return { kind: 'single', iso: iso.toLowerCase() }
}
